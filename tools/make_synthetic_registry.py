def write(path: Path, header, rows) -> None:
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(header)
        w.writerows(rows)


def tag_rows(items):
    service, industry = [], []
    for item in items:
        ident, industries, services, details = item[0], item[3], item[4], item[5]
        for ind in industries:
            industry.append([ident, "отрасль", "Верхний уровень", ind])
        for detail in details:
            service.append([ident, "услуга", services[0], detail])
    return service, industry


